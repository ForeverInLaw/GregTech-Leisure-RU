def translate_books():
    total_files = 0
    total_strings = 0

    for rel_path, data in TRANSLATIONS.items():
        src_path = os.path.join(SOURCE_DIR, rel_path)
        tgt_path = os.path.join(TARGET_DIR, rel_path)

        if not os.path.isfile(src_path):
            raise FileNotFoundError(f"Source file not found: {src_path}")

        with open(src_path, "r", encoding="utf-8") as sf:
            file_json = json.load(sf)

        # Update category or entry level fields
        if "name" in data:
            file_json["name"] = data["name"]
            total_strings += 1
        if "description" in data:
            file_json["description"] = data["description"]
            total_strings += 1

        # Update pages
        if "pages" in data:
            expected_pages = len(file_json.get("pages", []))
            provided_pages = len(data["pages"])
            if expected_pages != provided_pages:
                raise ValueError(
                    f"Page count mismatch in {rel_path}: expected {expected_pages}, got {provided_pages}"
                )

            for idx, page_trans in enumerate(data["pages"]):
                target_page = file_json["pages"][idx]
                for k, v in page_trans.items():
                    target_page[k] = v
                    total_strings += 1

        # Write to target directory
        os.makedirs(os.path.dirname(tgt_path), exist_ok=True)
        with open(tgt_path, "w", encoding="utf-8") as tf:
            json.dump(file_json, tf, ensure_ascii=False, indent=2)
            tf.write("\n")

        total_files += 1

    print(f"Successfully translated {total_files} files with {total_strings} strings.")


if __name__ == "__main__":
    translate_books()
